#!/usr/bin/env python3
"""Generates src/width_table.zig from Python's bundled Unicode database.

    python3 tools/gen_width.py > src/width_table.zig
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def is_zero(cp):
    if cp == 0x00AD:  # soft hyphen renders as a hyphen
        return False
    if 0x1160 <= cp <= 0x11FF:  # Hangul medial vowels and final consonants join the syllable
        return True
    if cp == 0x200B:  # zero width space
        return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")


def is_wide(cp):
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F")


def emit(name, rs):
    print(f"pub const {name} = [_][2]u21{{")
    for lo, hi in rs:
        print(f"    .{{ 0x{lo:X}, 0x{hi:X} }},")
    print("};")


print(f"//! Generated by tools/gen_width.py from Unicode {unicodedata.unidata_version}. Do not edit.")
print()
print("/// Codepoints that take no column of their own (combining marks, format characters).")
emit("zero", ranges(is_zero))
print()
print("/// Codepoints that take two columns (East Asian wide and fullwidth, most emoji).")
emit("wide", ranges(lambda cp: is_wide(cp) and not is_zero(cp)))
